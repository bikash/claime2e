using System.Globalization;

namespace JbAutoAi;

/// Dutch-first UI with English as the secondary language (FR-8.6).
///
/// The culture itself rides on ASP.NET's own RequestLocalization cookie, so
/// `CultureInfo.CurrentUICulture` is already correct by the time a page renders —
/// this class only holds the strings.
///
/// ponytail: one dictionary, not .resx. Two languages and ~120 keys do not need
/// satellite assemblies or a translation toolchain. Upgrade path if a third
/// language or an external translation vendor arrives: swap the dictionary for
/// IStringLocalizer, keep the T() call sites.
public static class I18n
{
    public const string CookieName = "lang";
    public static readonly string[] Supported = ["nl", "en"];

    public static string Current =>
        CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "en" ? "en" : "nl";

    public static bool IsDutch => Current == "nl";

    /// Language name for prompts, so model output follows the UI toggle.
    public static string PromptLanguage => IsDutch ? "Nederlands" : "English";

    /// Display formatting only. Parsing stays invariant everywhere (Program.cs) —
    /// this exists so a Dutch reader is not shown "€ 1,950" and reads one thousand
    /// nine hundred fifty as one point nine five.
    static CultureInfo Fmt => CultureInfo.GetCultureInfo(IsDutch ? "nl-NL" : "en-GB");

    public static string Money(double? amount) =>
        amount is { } v ? "€ " + v.ToString("N0", Fmt) : "—";

    public static string Money2(double? amount) =>
        amount is { } v ? "€ " + v.ToString("N2", Fmt) : "—";

    public static string T(string key) =>
        Strings.TryGetValue(key, out var pair) ? (IsDutch ? pair.Nl : pair.En) : key;

    public static string T(string key, params object?[] args) =>
        string.Format(CultureInfo.InvariantCulture, T(key), args);

